"""Generate the v1 voiceover with Kokoro (local TTS, the engine VoiceStudio also ships).

One clip per beat, so beat boundaries are known exactly and no speech-to-text pass
is needed. Writes audio.wav, timing.json (per-beat spans) and timing.ts (perSegment).

Usage: python generate.py <kokoro-v1.0.onnx> <voices-v1.0.bin>
"""

import json
import sys
from pathlib import Path

import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

LEAD_S = 0.35  # silence before a segment's first line (covers the fade transition)
GAP_S = 0.45  # silence between beats inside a segment
TAIL_S = 0.55  # silence after a segment's last line
ADVANCE_LEAD_S = 0.12  # fire an internal advance this long before the next line starts

here = Path(__file__).parent
script = json.loads((here / "script.json").read_text())
kokoro = Kokoro(sys.argv[1], sys.argv[2])

chunks, spans, per_segment = [], [], {}
sample_rate = None
cursor = 0.0
for segment_id, lines in script["segments"]:
    segment_start = cursor
    advances = []

    def silence(seconds):
        global cursor
        chunks.append(np.zeros(int(seconds * sample_rate), dtype=np.float32))
        cursor += seconds

    for index, line in enumerate(lines):
        samples, rate = kokoro.create(line, voice=script["voice"], speed=script["speed"], lang="en-gb")
        sample_rate = sample_rate or rate
        if index == 0:
            silence(LEAD_S)
        else:
            silence(GAP_S)
            advances.append(round(cursor - segment_start - ADVANCE_LEAD_S, 2))
        start = cursor
        chunks.append(samples.astype(np.float32))
        cursor += len(samples) / sample_rate
        spans.append({"segment": segment_id, "beat": index, "text": line, "start": round(start, 3), "end": round(cursor, 3)})
    silence(TAIL_S)
    advances.append(round(cursor - segment_start, 2))
    per_segment[segment_id] = advances

sf.write(here / "audio.wav", np.concatenate(chunks), sample_rate)
(here / "timing.json").write_text(json.dumps({"beats": spans, "length_s": round(cursor, 3)}, indent=2, ensure_ascii=False) + "\n")
(here / "timing.ts").write_text(
    "// Generated by generate.py. Segment-relative advance times in seconds.\n"
    "export const perSegment = " + json.dumps(per_segment, indent="\t") + ";\n"
)
print(json.dumps(per_segment, indent=1))
print("length_s", round(cursor, 2))
